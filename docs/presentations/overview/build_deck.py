def write_html() -> list[Path]:
    (HERE / "deck.css").write_text(CSS.lstrip(), encoding="utf-8")
    sdir = HERE / "slides"
    sdir.mkdir(exist_ok=True)
    for old in sdir.glob("*.html"):
        old.unlink()
    paths = []
    for i, s in enumerate(SLIDES, 1):
        p = sdir / f"{i:02d}.html"
        p.write_text(page(i, s), encoding="utf-8")
        paths.append(p)
    (HERE / "index.html").write_text(index_html(), encoding="utf-8")
    return paths


# Runs inside the page: report overflow and undersized text.
CHECK_JS = r"""
() => {
  const problems = [];
  const slide = document.querySelector('.slide');
  const sr = slide.getBoundingClientRect();
  const content = document.querySelector('.content');
  if (content.scrollHeight > content.clientHeight + 1)
    problems.push(`content overflows by ${content.scrollHeight - content.clientHeight}px`);
  for (const el of slide.querySelectorAll('*')) {
    const r = el.getBoundingClientRect();
    if (r.width === 0 || r.height === 0) continue;
    if (r.right > sr.right - 40 + 1 || r.bottom > sr.bottom + 1)
      problems.push(`${el.tagName}.${el.className} outside slide (${Math.round(r.right)},${Math.round(r.bottom)})`);
    if (el.classList.contains('src') && el.scrollWidth > el.clientWidth + 1)
      problems.push(`footer source is truncated`);
    if ((el.tagName === 'PRE' || el.classList.contains('card') || el.classList.contains('node'))
        && (el.scrollWidth > el.clientWidth + 1 || el.scrollHeight > el.clientHeight + 1))
      problems.push(`${el.tagName}.${el.className} clips its text`);
    const hasText = [...el.childNodes].some(n => n.nodeType === 3 && n.textContent.trim());
    if (!hasText) continue;
    const fs = parseFloat(getComputedStyle(el).fontSize);
    const inFoot = !!el.closest('.foot');
    const isCode = !!el.closest('pre, code, .mono, .q');
    const min = (inFoot || isCode) ? 20 : 24;
    if (fs < min - 0.01)
      problems.push(`text "${el.textContent.trim().slice(0, 30)}" is ${fs}px (< ${min})`);
  }
  return problems;
}
"""


def render(paths: list[Path]) -> int:
    from playwright.sync_api import sync_playwright

    tdir = HERE / "thumbs"
    tdir.mkdir(exist_ok=True)
    for old in tdir.glob("*.png"):
        old.unlink()
    failures = 0
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        pg = browser.new_page(viewport={"width": W, "height": H})
        for i, p in enumerate(paths, 1):
            pg.goto(p.as_uri())
            pg.wait_for_load_state("load")
            probs = pg.evaluate(CHECK_JS)
            pg.screenshot(path=str(tdir / f"slide-{i:02d}.png"))
            for pr in probs:
                print(f"slide {i:02d}: {pr}")
            failures += len(probs)
        # PDF: all slides in one print document, one 1280x720 page each.
        bodies = []
        for p in paths:
            src = p.read_text(encoding="utf-8")
            m = re.search(r"(<section.*?</section>)", src, re.S)
            bodies.append(m.group(1))
        doc = ("<!DOCTYPE html><html><head><meta charset='utf-8'><style>" + CSS
               + "@page { size: 1280px 720px; margin: 0; }"
               + ".slide { page-break-after: always; break-after: page; }"
               + "</style></head><body>" + "\n".join(bodies) + "</body></html>")
        pg.set_content(doc, wait_until="load")
        pg.pdf(path=str(HERE / "slides.pdf"), width=f"{W}px", height=f"{H}px",
               print_background=True, margin={"top": "0", "right": "0", "bottom": "0", "left": "0"})
        browser.close()
    return failures


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--html", action="store_true", help="write HTML only (skip PNG/PDF/checks)")
    args = ap.parse_args()
    if not 12 <= len(SLIDES) <= 16:
        print(f"expected 12–16 slides, have {len(SLIDES)}", file=sys.stderr)
        return 1
    paths = write_html()
    print(f"wrote {len(paths)} slides, index.html, deck.css")
    if args.html:
        return 0
    failures = render(paths)
    print(f"rendered thumbs/ and slides.pdf; {failures} layout/size problem(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
