# ------------------------------------------------------------------- helpers


def code(text: str, cls: str = "") -> str:
    """Escape a code block; ``[[x]]`` highlights x, ``##x`` to end of line is a comment."""
    out = []
    for line in text.strip("\n").split("\n"):
        esc = html.escape(line, quote=False)
        esc = re.sub(r"\[\[(.+?)\]\]", r'<mark class="hl">\1</mark>', esc)
        esc = re.sub(r"(##.*)$", lambda m: f'<span class="cmt">{m.group(1)[2:]}</span>', esc)
        out.append(esc)
    style = f' class="{cls}"' if cls else ""
    return f"<pre{style}>" + "\n".join(out) + "</pre>"


def ul(*items: str, style: str = "") -> str:
    s = f' style="{style}"' if style else ""
    return f"<ul{s}>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


